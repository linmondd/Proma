def soften_lit(text: str) -> str:
    for pat, rep in LIT_SWAPS:
        text = re.sub(pat, rep, text)
    return text


def yellow_sex_para(para: str, chap_idx: int, para_idx: int) -> str:
    """给缺少浪叫的肉戏段补口语，避免千篇一律。"""
    if not SEX_RE.search(para):
        return para
    if HOT_RE.search(para) and para.count("啊") >= 2:
        return para
    # 已是结尾浪块则跳过
    if para.strip().startswith("---"):
        return para

    tags = [
        "啊啊啊……好深……别停……操……",
        "操我……再深一点……呃呃呃……要去……",
        "好湿……咕啾……好爽……啊啊啊啊啊……",
        "别抽出去……夹着……再操……呜啊啊……",
        "骚逼自己在吸……操……再快……",
        "顶那里……啊啊啊……要喷……喷了……",
        "好胀……好满……射进来……啊啊……",
        "叫出来……别忍……啊啊啊……操死我……",
    ]
    tag = tags[(chap_idx * 7 + para_idx * 3) % len(tags)]

    # 插进段落末尾，保持原叙事
    if para.endswith("”") or para.endswith('"'):
        return para + f"\n\n她（他）喘着补了一句，句尾全是肉：“{tag}”"
    return para + f" 她浪叫着要更多：“{tag}”"


def strip_loop(text: str) -> str:
    return LOOP_RE.sub("\n", text)


def inject_mid(text: str, block: str) -> str:
    if not block:
        return text
    # 避免重复注入
    marker = block.strip().split("\n", 2)[-1][:20]
    if marker and marker in text:
        return text
    # 插在文末既有---浪块之前；若无则文末
    idx = text.rfind("\n---\n")
    if idx != -1 and idx > len(text) // 3:
        return text[:idx] + block + text[idx:]
    return text.rstrip() + block


def process_chapter(path: Path, chap_idx: int) -> tuple[str, dict]:
    name = path.name
    raw = path.read_text(encoding="utf-8")
    stats = {"loop_stripped": False, "mid": False, "sex_touched": 0}

    text = raw
    if name in UNIQUE_TAILS:
        text = strip_loop(text)
        text = text.rstrip() + "\n\n---\n\n" + UNIQUE_TAILS[name]
        stats["loop_stripped"] = True

    text = soften_lit(text)

    paras = re.split(r"(\n\n+)", text)
    out: list[str] = []
    sex_i = 0
    for part in paras:
        if not part or part.startswith("\n"):
            out.append(part)
            continue
        if SEX_RE.search(part) and len(part) > 60:
            newp = yellow_sex_para(part, chap_idx, sex_i)
            if newp != part:
                stats["sex_touched"] += 1
            out.append(newp)
            sex_i += 1
        else:
            out.append(part)
    text = "".join(out)

    if name in MID_BLOCKS:
        new_text = inject_mid(text, MID_BLOCKS[name])
        if new_text != text:
            stats["mid"] = True
        text = new_text

    # 清理明显工业复读残留
    text = re.sub(r"(爽得要死，死不了，就继续被干，干到声音发飘：嗯……呃呃……再深一点……\n*){2,}", "", text)

    path.write_text(text, encoding="utf-8")
    cjk = len(re.findall(r"[\u4e00-\u9fff]", text))
    hot = len(re.findall(r"啊啊啊", text)) + len(re.findall(r"操我", text)) + len(re.findall(r"被操", text))
    stats["cjk"] = cjk
    stats["hot"] = hot
    return name, stats


def main() -> None:
    files = sorted(CHAP_DIR.glob("*.md"))
    print(f"processing {len(files)} chapters...")
    for i, p in enumerate(files, 1):
        name, st = process_chapter(p, i)
        print(f"{i:02d} {name}: loop={st['loop_stripped']} mid={st['mid']} sex+={st['sex_touched']} hot={st['hot']} cjk={st['cjk']}")


if __name__ == "__main__":
    main()
